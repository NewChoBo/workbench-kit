import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  formatManifestViolations,
  readWorkbenchExtensionManifestEntries,
  validateWorkbenchExtensionManifests,
} from './workbench-extension-manifest-utils.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lockPath = path.join(repoRoot, '.workbench', 'extensions.lock.json');

const extensionGroups = [
  {
    exportName: 'BUILTIN_WORKBENCH_EXTENSIONS',
    outputPath: path.join(
      repoRoot,
      'packages',
      'shell-react',
      'src',
      'extensions',
      'builtin-extensions.ts',
    ),
    prefix: 'builtin.',
  },
  {
    exportName: 'SAMPLE_WORKBENCH_EXTENSIONS',
    outputPath: path.join(repoRoot, 'examples', 'workbench-sample', 'src', 'sample-extensions.ts'),
    prefix: 'samples.',
  },
];

const manifestEntries = await readWorkbenchExtensionManifestEntries(repoRoot);
const manifestViolations = validateWorkbenchExtensionManifests(manifestEntries, repoRoot);

if (manifestViolations.length > 0) {
  console.error('Workbench extension manifest check failed.');
  console.error(formatManifestViolations(manifestViolations));
  process.exit(1);
}

const groups = extensionGroups.map(({ exportName, outputPath, prefix }) => ({
  exportName,
  extensions: readExtensionGroup(prefix, outputPath),
  outputPath,
}));

for (const { exportName, extensions, outputPath } of groups) {
  const moduleImports = extensions
    .filter(({ hasModule }) => hasModule)
    .map(
      ({ importName, modulePath }) =>
        `import * as ${importName} from ${JSON.stringify(modulePath)};`,
    );
  const content = [
    "import type { WorkbenchExtensionDescription } from '@workbench-kit/workbench-core';",
    ...moduleImports,
    '',
    '// This file is generated by scripts/bundle-workbench-extensions.mjs.',
    '// Do not edit it by hand.',
    '',
    `export const ${exportName} = [`,
    ...extensions.map(formatExtensionDescription),
    `] as unknown as readonly WorkbenchExtensionDescription[];`,
    '',
  ].join('\n');

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, await formatTypeScript(`${content.trimEnd()}\n`));
}

const lockExtensions = Object.fromEntries(
  groups
    .flatMap(({ extensions }) => extensions)
    .map(({ manifest }) => [
      manifest.id,
      {
        integrity: `sha256:${createHash('sha256').update(stableStringify(manifest)).digest('hex')}`,
        version: manifest.version,
      },
    ])
    .sort(([left], [right]) => left.localeCompare(right)),
);

await mkdir(path.dirname(lockPath), { recursive: true });
await writeFile(
  lockPath,
  `${JSON.stringify({ lockfileVersion: 1, extensions: lockExtensions }, null, 2)}\n`,
);

function readExtensionGroup(prefix, outputPath) {
  return manifestEntries
    .filter(({ directory }) => directory.startsWith(prefix))
    .map(({ directory, extensionPath, manifest, modulePath }) => ({
      extensionPath,
      hasModule: manifest.activationEvents.length > 0,
      importName: toModuleImportName(directory),
      manifest,
      modulePath: relativeImportPath(path.dirname(outputPath), modulePath),
    }));
}

function relativeImportPath(fromDirectory, targetPath) {
  const relativePath = path
    .relative(fromDirectory, targetPath)
    .replaceAll(path.sep, '/')
    .replace(/\.(?:[cm]?ts|tsx)$/u, '.js');
  return relativePath.startsWith('.') ? relativePath : `./${relativePath}`;
}

function formatExtensionDescription({ extensionPath, hasModule, importName, manifest }) {
  return [
    '  {',
    `    extensionPath: ${JSON.stringify(extensionPath)},`,
    `    manifest: ${formatManifest(manifest, 4)},`,
    ...(hasModule ? [`    module: ${importName},`] : []),
    '  },',
  ].join('\n');
}

function formatManifest(manifest, indent) {
  const padding = ' '.repeat(indent);
  return JSON.stringify(manifest, null, 2).replaceAll('\n', `\n${padding}`);
}

function toModuleImportName(directory) {
  const words = directory.split(/[^a-zA-Z0-9]+/).filter(Boolean);
  const [first = 'extension', ...rest] = words;
  const suffix = rest.map((word) => `${word[0].toUpperCase()}${word.slice(1)}`).join('');

  return `${first}${suffix}Module`;
}

async function formatTypeScript(content) {
  try {
    const prettier = await import('prettier');

    return await prettier.format(content, {
      parser: 'typescript',
      printWidth: 100,
      singleQuote: true,
      trailingComma: 'all',
    });
  } catch {
    return content;
  }
}

function stableStringify(value) {
  return JSON.stringify(sortValue(value));
}

function sortValue(value) {
  if (Array.isArray(value)) {
    return value.map((entry) => sortValue(entry));
  }

  if (typeof value === 'object' && value !== null) {
    const sorted = {};
    for (const key of Object.keys(value).sort((left, right) => left.localeCompare(right))) {
      sorted[key] = sortValue(value[key]);
    }
    return sorted;
  }

  return value;
}
